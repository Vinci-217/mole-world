def crown(x, y, z, width, height):
    # A genuine crown-shaped relief rather than an invented red-nose facade.
    silhouette = [(-.5, 0), (.5, 0), (.52, .25), (.55, .83), (.24, .52), (0, 1), (-.24, .52), (-.55, .83), (-.52, .25)]
    verts = [(x + xx * width, yy, z + zz * height) for yy in [y - .1, y + .1] for xx, zz in silhouette]
    count = len(silhouette)
    faces = [tuple(range(count - 1, -1, -1)), tuple(range(count, count * 2))] + [(i, (i+1)%count, (i+1)%count+count, i+count) for i in range(count)]
    polygon_mesh('Gold crown relief', verts, faces, M['gold'])
    box('Crown lower rolled band', (x, y - .08, z + .08 * height), (width * 1.1, .25, .16 * height), M['gold'], .07)
    sphere('Crown ruby jewel', (x, y - .24, z + height * .25), width * .09, M['ruby'], (1, .45, 1.25))
    for dx, dh in [(-.55,.83),(0,1),(.55,.83)]:
        sphere('Crown tip pearl', (x + dx * width, y, z + dh * height), width * .065, M['gold'])


