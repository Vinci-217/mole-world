# Apply transforms and create physical-size UVs for the primitive stone/wood
# surfaces. The custom roof lathe UVs are retained.
for obj in list(bpy.context.scene.objects):
    if obj.type!='MESH':
        continue
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(obj.data)
    bm.free()
    bpy.context.view_layer.objects.active=obj
    obj.select_set(True)
    bpy.ops.object.transform_apply(location=True,rotation=True,scale=True)
    obj.select_set(False)
    if not obj.get('preserve_uv'):
        uv=obj.data.uv_layers.active or obj.data.uv_layers.new(name='Surface coordinates')
        for polygon in obj.data.polygons:
            axis=max(range(3),key=lambda i:abs(polygon.normal[i]))
            for loop in polygon.loop_indices:
                p=obj.data.vertices[obj.data.loops[loop].vertex_index].co
                a,b=(p.x,p.y) if axis==2 else (p.x,p.z) if axis==1 else (p.y,p.z)
                uv.data[loop].uv=(a/3,b/3)

