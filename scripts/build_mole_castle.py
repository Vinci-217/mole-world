def generate_surface_maps():
    """Tileable colour and tangent normals, at a physical three-metre scale."""
    TEX.mkdir(parents=True, exist_ok=True)
    n = 1024
    yy, xx = np.mgrid[0:n, 0:n].astype(np.float32) / n
    rng = np.random.default_rng(1989)
    grain = rng.normal(0, 1, (n, n)).astype(np.float32)
    cloud = (np.sin(xx * math.tau * 7) * np.cos(yy * math.tau * 5)
             + .5 * np.sin((xx + yy) * math.tau * 19))

    def save(name, color, height, strength):
        rgba = np.ones((n, n, 4), dtype=np.float32)
        rgba[:, :, :3] = np.clip(color, 0, 1)
        image = bpy.data.images.new(name, width=n, height=n, alpha=False)
        image.pixels.foreach_set(rgba.ravel())
        image.filepath_raw = str(TEX / (name + '.png'))
        image.file_format = 'PNG'
        image.save()
        dy, dx = np.gradient(height)
        normals = np.dstack((-dx * strength, -dy * strength, np.ones_like(dx)))
        normals /= np.linalg.norm(normals, axis=2, keepdims=True)
        rgba[:, :, :3] = normals * .5 + .5
        normal = bpy.data.images.new(name + '-normal', width=n, height=n, alpha=False)
        normal.colorspace_settings.name = 'Non-Color'
        normal.pixels.foreach_set(rgba.ravel())
        normal.filepath_raw = str(TEX / (name + '-normal.png'))
        normal.file_format = 'PNG'
        normal.save()

    row = np.floor(yy * 6)
    tx = (xx * 3 + (row % 2) * .5) % 1
    ty = (yy * 6) % 1
    edge = np.minimum(np.minimum(tx, 1 - tx), np.minimum(ty, 1 - ty))
    stone = np.clip((edge - .012) / .035, 0, 1)
    block = .025 * np.sin(np.floor(xx * 3 + (row % 2) * .5) * 14 + row * 53)
    shade = stone * .10 + block + cloud * .009 + grain * .003
    color = np.stack((.72 + shade, .62 + shade, .44 + shade), axis=2)
    save('limestone', color, stone * .13 + cloud * .003 + grain * .001, 46)

    row = np.floor(yy * 8)
    tx = (xx * 6 + (row % 2) * .5) % 1
    ty = (yy * 8) % 1
    edge = np.minimum(tx, 1 - tx)
    tile = np.clip(edge / .045, 0, 1) * np.clip(ty / .06, 0, 1)
    tile_shade = .035 * np.sin(np.floor(xx * 6 + (row % 2) * .5) * 3.7 + row * 14)
    shade = tile * .085 + tile_shade + cloud * .013 + grain * .005
    color = np.stack((.57 + shade, .13 + shade * .48, .065 + shade * .23), axis=2)
    save('terracotta', color, tile * .13 + np.sin(tx * math.pi) * .025 + grain * .001, 34)

    plank = np.floor(xx * 7)
    wood = np.sin(xx * math.tau * 93 + np.sin(yy * math.tau * 4) * 3)
    shade = wood * .013 + cloud * .008 + .018 * np.sin(plank * 13)
    color = np.stack((.32 + shade, .17 + shade * .7, .065 + shade * .4), axis=2)
    joint = np.clip(np.minimum((xx * 7) % 1, 1 - (xx * 7) % 1) / .025, 0, 1)
    save('oak', color * (.55 + joint[:, :, None] * .45), joint * .05 + wood * .008, 12)


generate_surface_maps()


def material(name, color, roughness=.7, metallic=0, texture=None, normal_strength=.35, emission=None):
    result = bpy.data.materials.new(name)
    result.use_nodes = True
    nodes = result.node_tree.nodes
    principled = next(n for n in nodes if n.type == 'BSDF_PRINCIPLED')
    principled.inputs['Base Color'].default_value = (*color, 1)
    principled.inputs['Roughness'].default_value = roughness
    principled.inputs['Metallic'].default_value = metallic
    if texture:
        tex_file = TEX / (texture + '.png')
        if not tex_file.exists():
            raise RuntimeError('Missing required surface map: ' + str(tex_file))
        image = nodes.new('ShaderNodeTexImage')
        image.image = bpy.data.images.load(str(tex_file))
        result.node_tree.links.new(image.outputs['Color'], principled.inputs['Base Color'])
        normal_file = TEX / (texture + '-normal.png')
        if normal_file.exists():
            normal_image = nodes.new('ShaderNodeTexImage')
            normal_image.image = bpy.data.images.load(str(normal_file))
            normal_image.image.colorspace_settings.name = 'Non-Color'
            normal = nodes.new('ShaderNodeNormalMap')
            normal.inputs['Strength'].default_value = normal_strength
            result.node_tree.links.new(normal_image.outputs['Color'], normal.inputs['Color'])
            result.node_tree.links.new(normal.outputs['Normal'], principled.inputs['Normal'])
    if emission:
        principled.inputs['Emission Color'].default_value = (*emission, 1)
        principled.inputs['Emission Strength'].default_value = .7
    result.diffuse_color = (*color, 1)
    return result


