def roof(name, x, y, z, radius, height):
    # A flared, rounded roof profile gives the original illustration's generous
    # eaves. Tile courses are represented by PBR maps and narrow geometric lips.
    rings = [(0, radius), (.18, radius * .99), (.45, radius * .91), (height * .4, radius * .64), (height * .75, radius * .29), (height, .04)]
    n = 64
    verts = [(x + math.cos(i / n * math.tau) * r, y + math.sin(i / n * math.tau) * r, z + h) for h, r in rings for i in range(n)]
    faces = [(j * n + i, j * n + (i + 1) % n, (j + 1) * n + (i + 1) % n, (j + 1) * n + i) for j in range(len(rings) - 1) for i in range(n)]
    obj = polygon_mesh(name, verts, faces, M['roof'], True)
    layer = obj.data.uv_layers.new(name='Roof tile coordinates')
    for j in range(len(rings) - 1):
        for i in range(n):
            poly = obj.data.polygons[j * n + i]
            coords = [(i / n * 4, rings[j][0] / 4), ((i + 1) / n * 4, rings[j][0] / 4), ((i + 1) / n * 4, rings[j + 1][0] / 4), (i / n * 4, rings[j + 1][0] / 4)]
            for loop, uv in zip(poly.loop_indices, coords):
                layer.data[loop].uv = uv
            poly.use_smooth = True
    torus(name + ' gold eave', (x, y, z + .025), radius, .09, M['gold'])
    def profile(h):
        for (ha, ra), (hb, rb) in zip(rings[:-1], rings[1:]):
            if ha <= h <= hb:
                return ra + (rb - ra) * (h - ha) / (hb - ha)
        return .04
    # Individually lapped and cambered roof tiles, including real thickness.
    vertices, tile_faces = [], []
    courses = max(5, round(height / .46))
    for row in range(courses):
        lo = .2 + (height - .45) * row / courses
        hi = .2 + (height - .45) * (row + 1) / courses + .045
        count = max(8, round(math.tau * profile(lo) / .48))
        for i in range(count):
            a = math.tau * (i + (row % 2) * .5 + .025) / count
            b = a + math.tau * .95 / count
            start = len(vertices)
            for under in [True, False]:
                for h in [lo, hi]:
                    for k in range(5):
                        angle = a + (b - a) * k / 4
                        proud = .014 if under else .055 + .022 * math.sin(k / 4 * math.pi)
                        r = profile(h) + proud
                        vertices.append((x + math.cos(angle) * r, y + math.sin(angle) * r, z + h))
            for k in range(4):
                tile_faces.extend([(start+k,start+k+1,start+k+6,start+k+5),
                                   (start+10+k,start+15+k,start+16+k,start+11+k),
                                   (start+k,start+10+k,start+11+k,start+k+1),
                                   (start+5+k,start+6+k,start+16+k,start+15+k)])
            tile_faces.extend([(start,start+5,start+15,start+10),
                               (start+4,start+14,start+19,start+9)])
    tile_obj = polygon_mesh(name + ' individually lapped clay tiles', vertices, tile_faces, M['roof'])
    for p in tile_obj.data.polygons:
        p.use_smooth = True
    sphere(name + ' finial', (x, y, z + height + .09), .13, M['gold'])


def tower(x, y, radius, wall_height, roof_height, windows=True):
    cylinder('Ivory round tower', (x, y, wall_height / 2), radius, wall_height, M['stone'], 48)
    for h, r, depth in [(.3, radius + .18, .36), (3.2, radius + .09, .18), (wall_height - 2.4, radius + .14, .22), (wall_height - .28, radius + .22, .3)]:
        cylinder('Tower carved stone band', (x, y, h), r, depth, M['trim'], 48)
    cylinder('Tower gold cornice', (x, y, wall_height - .04), radius + .28, .12, M['gold'], 48)
    roof('Red conical tower roof', x, y, wall_height, radius + .5, roof_height)
    if windows:
        window(x, y - radius - .025, wall_height - 5.1, .77, 1.6)
        window(x, y - radius - .03, 3.5, .66, 1.4)
    # Repeated small corbels under the eave, a distinctive illustrated detail.
    for i in range(12):
        angle = i / 12 * math.tau
        box('Tower cornice corbel', (x + math.cos(angle) * (radius + .08), y + math.sin(angle) * (radius + .08), wall_height - .65), (.22, .22, .58), M['gold'], .04)


def merlons(x0, x1, y, base, count):
    for i in range(count):
        x = x0 + (x1 - x0) * i / max(1, count - 1)
        box('Rounded crenellation', (x, y, base + .43), (.78, .85, .85), M['trim'], .085)
        box('Gold crenellation lip', (x, y, base + .03), (1.0, 1.0, .12), M['gold'], .025)


