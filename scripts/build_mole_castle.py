def finish(obj, mat, bevel=0, smooth=False, preserve_uv=False):
    obj.data.materials.append(mat)
    if bevel:
        modifier = obj.modifiers.new('Soft carved edges', 'BEVEL')
        modifier.width = bevel
        modifier.segments = 2
        modifier.affect = 'EDGES'
        bpy.context.view_layer.objects.active = obj
        bpy.ops.object.modifier_apply(modifier=modifier.name)
    if smooth:
        for face in obj.data.polygons:
            face.use_smooth = len(face.vertices) <= 4
    obj['preserve_uv'] = preserve_uv
    return obj


def box(name, position, size, mat, bevel=.035, rotation=None):
    bpy.ops.mesh.primitive_cube_add(size=1, location=position)
    obj = bpy.context.object
    obj.name = name
    obj.scale = size
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    if rotation:
        obj.rotation_euler = rotation
    return finish(obj, mat, bevel)


def cylinder(name, position, radius, depth, mat, vertices=40, rotation=None, top_radius=None):
    if top_radius is None:
        bpy.ops.mesh.primitive_cylinder_add(vertices=vertices, radius=radius, depth=depth, location=position)
    else:
        bpy.ops.mesh.primitive_cone_add(vertices=vertices, radius1=radius, radius2=top_radius, depth=depth, location=position)
    obj = bpy.context.object
    obj.name = name
    if rotation:
        obj.rotation_euler = rotation
    if obj.data.uv_layers:
        for uv in obj.data.uv_layers.active.data:
            uv.uv.x *= 2 * math.pi * radius / 3
            uv.uv.y *= max(depth, 1) / 3
    return finish(obj, mat, smooth=True, preserve_uv=True)


def sphere(name, position, radius, mat, scale=(1, 1, 1)):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=20, ring_count=10, radius=radius, location=position)
    obj = bpy.context.object
    obj.name = name
    obj.scale = scale
    return finish(obj, mat, smooth=True)


def torus(name, position, radius, thickness, mat, rotation=None, segments=48):
    bpy.ops.mesh.primitive_torus_add(major_segments=segments, minor_segments=6, location=position, major_radius=radius, minor_radius=thickness)
    obj = bpy.context.object
    obj.name = name
    if rotation:
        obj.rotation_euler = rotation
    return finish(obj, mat, smooth=True)


def beam(name, start, end, radius, mat, sides=8):
    a, b = Vector(start), Vector(end)
    obj = cylinder(name, (a + b) / 2, radius, (b - a).length, mat, sides)
    obj.rotation_euler = (b - a).to_track_quat('Z', 'Y').to_euler()
    return obj


def polygon_mesh(name, vertices, faces, mat, preserve_uv=False):
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(vertices, [], faces)
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)
    return finish(obj, mat, preserve_uv=preserve_uv)


def arch_shape(width, height, segments=24):
    radius = width / 2
    shoulder = height - radius
    shape = [(-radius, 0), (radius, 0), (radius, shoulder)]
    for i in range(1, segments + 1):
        angle = i / segments * math.pi
        shape.append((math.cos(angle) * radius, shoulder + math.sin(angle) * radius))
    return shape


def filled_arch(name, x, y, base, width, height, depth, mat):
    shape = arch_shape(width, height)
    count = len(shape)
    verts = [(x + xx, y + yy, base + zz) for yy in [-depth / 2, depth / 2] for xx, zz in shape]
    faces = [tuple(range(count - 1, -1, -1)), tuple(range(count, count * 2))]
    faces += [(i, (i + 1) % count, (i + 1) % count + count, i + count) for i in range(count)]
    return polygon_mesh(name, verts, faces, mat)


def arch_frame(name, x, y, base, width, height, thickness, mat):
    radius = width / 2
    shoulder = base + height - radius
    for side in [-1, 1]:
        box(name + ' jamb', (x + side * (radius + thickness / 2), y, (base + shoulder) / 2), (thickness, .28, shoulder - base), mat, .025)
    for i in range(20):
        a = i / 20 * math.pi
        b = (i + 1) / 20 * math.pi
        inner, outer = radius, radius + thickness
        vertices = [(x + math.cos(angle) * r, yy, shoulder + math.sin(angle) * r) for yy in [y - .15, y + .15] for angle, r in [(a, inner), (a, outer), (b, outer), (b, inner)]]
        faces = [(0, 1, 2, 3), (7, 6, 5, 4), (0, 4, 5, 1), (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)]
        polygon_mesh(name + ' curved arch', vertices, faces, mat)


